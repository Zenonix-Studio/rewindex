#!/usr/bin/env node
"use strict";

const assert = require("assert");
const fs = require("fs");
const os = require("os");
const path = require("path");
const { spawnSync } = require("child_process");

const CLI = path.join(__dirname, "dist", "cli.js");
const tmpRoot = fs.mkdtempSync(path.join(os.tmpdir(), "rewindex-install-"));
let passed = 0;

function ok(message) {
  passed++;
  console.log(`  ok - ${message}`);
}

function run(home, ...args) {
  return spawnSync("node", [CLI, ...args], {
    env: { ...process.env, CODEX_HOME: home, REWINDEX_HOME: path.join(home, "rewindex-data") },
    encoding: "utf8",
  });
}

function skillFile(home) {
  return path.join(home, "skills", "rewindex", "SKILL.md");
}

try {
  const home = path.join(tmpRoot, "codex-home");
  const install = run(home, "install");
  assert.strictEqual(install.status, 0, install.stderr);
  assert.ok(fs.existsSync(skillFile(home)), "install must create the rewindex skill");

  const skill = fs.readFileSync(skillFile(home), "utf8");
  assert.match(skill, /generated by rewindex/i);
  assert.match(skill, /name: rewindex/);
  assert.match(skill, /\$rewindex list/);
  assert.match(skill, /\$rewindex diff <number\|id>/);
  assert.match(skill, /\$rewindex restore <number\|id>/);
  assert.match(skill, /\$rewindex undo/);
  assert.ok(skill.includes(CLI), "skill must use the installed CLI's absolute path");
  assert.match(skill, /-C "\$PWD"/);
  assert.match(skill, /hexadecimal/i);
  assert.match(skill, /number from `1` through `50`/i);
  assert.match(skill, /explicit confirmation/i);
  assert.match(skill, /restore.+-y/is);
  ok("install creates a self-contained rewindex skill");

  const reinstall = run(home, "install");
  assert.strictEqual(reinstall.status, 0, reinstall.stderr);
  const hooks = JSON.parse(fs.readFileSync(path.join(home, "hooks.json"), "utf8"));
  assert.strictEqual(hooks.hooks.PreToolUse.length, 1);
  assert.strictEqual(hooks.hooks.UserPromptSubmit.length, 1);
  assert.strictEqual(fs.readFileSync(skillFile(home), "utf8"), skill);
  ok("reinstall is idempotent for hooks and skill");

  const otherSkill = path.join(home, "skills", "other", "SKILL.md");
  fs.mkdirSync(path.dirname(otherSkill), { recursive: true });
  fs.writeFileSync(otherSkill, "unrelated\n");
  const uninstall = run(home, "uninstall");
  assert.strictEqual(uninstall.status, 0, uninstall.stderr);
  assert.ok(!fs.existsSync(skillFile(home)), "uninstall must remove its owned skill");
  assert.strictEqual(fs.readFileSync(otherSkill, "utf8"), "unrelated\n");
  ok("uninstall removes only the owned rewindex skill");

  const conflictHome = path.join(tmpRoot, "conflict-home");
  const conflictSkill = skillFile(conflictHome);
  fs.mkdirSync(path.dirname(conflictSkill), { recursive: true });
  fs.writeFileSync(conflictSkill, "user-owned skill\n");
  const conflict = run(conflictHome, "install");
  assert.notStrictEqual(conflict.status, 0, "install must reject an unowned rewindex skill");
  assert.strictEqual(fs.readFileSync(conflictSkill, "utf8"), "user-owned skill\n");
  assert.ok(!fs.existsSync(path.join(conflictHome, "hooks.json")), "conflict must fail before hooks change");
  ok("install never overwrites an unowned skill");

  console.log(`INSTALL-CHECK PASSED (${passed} scenarios)`);
} finally {
  fs.rmSync(tmpRoot, { recursive: true, force: true });
}
